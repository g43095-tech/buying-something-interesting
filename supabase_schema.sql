-- 3. טבלת פוסטים בערוץ
CREATE TABLE IF NOT EXISTS public.posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content TEXT NOT NULL DEFAULT '',
  media_type TEXT NOT NULL DEFAULT 'none' CHECK (media_type IN ('none', 'image', 'video', 'audio', 'file')),
  media_url TEXT DEFAULT '',
  media_name TEXT DEFAULT '',
  category TEXT DEFAULT 'כללי',
  is_pinned BOOLEAN NOT NULL DEFAULT FALSE,
  reactions JSONB NOT NULL DEFAULT '{"👍": 0, "❤️": 0, "🔥": 0}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.posts ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public can read posts"
  ON public.posts FOR SELECT
  TO anon, authenticated
  USING (true);

CREATE POLICY "Admins can insert posts"
  ON public.posts FOR INSERT
  TO authenticated
  WITH CHECK (EXISTS (SELECT 1 FROM public.admins WHERE email = auth.jwt() ->> 'email'));

CREATE POLICY "Admins can update posts"
  ON public.posts FOR UPDATE
  TO authenticated
  USING (EXISTS (SELECT 1 FROM public.admins WHERE email = auth.jwt() ->> 'email'))
  WITH CHECK (EXISTS (SELECT 1 FROM public.admins WHERE email = auth.jwt() ->> 'email'));

CREATE POLICY "Admins can delete posts"
  ON public.posts FOR DELETE
  TO authenticated
  USING (EXISTS (SELECT 1 FROM public.admins WHERE email = auth.jwt() ->> 'email'));

-- 4. פונקציה בטוחה להוספת תגובה (אימוג'י) ע"י גולשים ללא הרשאת כתיבה מלאה
CREATE OR REPLACE FUNCTION public.increment_reaction(p_post_id BIGINT, p_emoji TEXT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_allowed TEXT[] := ARRAY['👍', '❤️', '🔥', '👏', '😮'];
  v_updated JSONB;
BEGIN
  IF NOT (p_emoji = ANY(v_allowed)) THEN
    RAISE EXCEPTION 'Emoji not allowed';
  END IF;

  UPDATE public.posts
  SET reactions = jsonb_set(
    COALESCE(reactions, '{}'::jsonb),
    ARRAY[p_emoji],
    to_jsonb(COALESCE((reactions ->> p_emoji)::int, 0) + 1)
  )
  WHERE id = p_post_id
  RETURNING reactions INTO v_updated;

  RETURN v_updated;
END;
$$;

GRANT EXECUTE ON FUNCTION public.increment_reaction(BIGINT, TEXT) TO anon, authenticated;

