-- 1. טבלת מנהלים מורשים (רק המיילים שברשימה יוכלו לפרסם/לערוך/למחוק)
CREATE TABLE IF NOT EXISTS public.admins (
  email TEXT PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.admins ENABLE ROW LEVEL SECURITY;

-- מנהלים יכולים לראות את רשימת המנהלים (נדרש לבדיקת הרשאה בצד הלקוח)
CREATE POLICY "Admins can read own status"
  ON public.admins FOR SELECT
  TO authenticated
  USING (auth.jwt() ->> 'email' = email);

-- 2. הגדרות הערוץ (כותרת, תיאור, לוגו)
