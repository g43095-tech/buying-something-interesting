-- 4. פונקציה בטוחה להוספת תגובה (רק למשתמשים מחוברים)
CREATE OR REPLACE FUNCTION public.increment_reaction(p_post_id BIGINT, p_emoji TEXT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_allowed TEXT[] := ARRAY['👍', '❤️', '🔥', '👏', '😮'];
  v_updated JSONB;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  IF NOT (p_emoji = ANY(v_allowed)) THEN
    RAISE EXCEPTION 'Emoji not allowed';
  END IF;

  UPDATE public.posts
  SET reactions = jsonb_set(
    COALESCE(reactions, '{}'::jsonb),
    ARRAY[p_emoji],
    to_jsonb(COALESCE((reactions ->> p_emoji)::int, 0) + 1)
  )
  WHERE id = p_post_id
  RETURNING reactions INTO v_updated;

  RETURN v_updated;
END;
$$;

REVOKE ALL ON FUNCTION public.increment_reaction(BIGINT, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.increment_reaction(BIGINT, TEXT) TO authenticated;

