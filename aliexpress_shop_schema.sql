-- 1. מנהלי החנות (משתמש גם את טבלת המנהלים הקיימת בפרויקט, אם קיימת)
CREATE TABLE IF NOT EXISTS public.admins (
  email TEXT PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.admins ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Admins can read own status" ON public.admins;
CREATE POLICY "Admins can read own status"
  ON public.admins FOR SELECT
  TO authenticated
  USING (auth.jwt() ->> 'email' = email);

-- 2. מוצרים: כל מוצר שנמשך מהאוטומציה נכנס במצב 'ממתין' ומחכה לאישור מנהל
CREATE TABLE IF NOT EXISTS public.shop_products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  external_id TEXT UNIQUE NOT NULL,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  image_url TEXT NOT NULL DEFAULT '',
  category TEXT NOT NULL DEFAULT 'כללי',
  price NUMERIC(10, 2) NOT NULL DEFAULT 0,
  original_price NUMERIC(10, 2) NOT NULL DEFAULT 0,
  discount_percent INT NOT NULL DEFAULT 0,
  currency TEXT NOT NULL DEFAULT 'ILS',
  rating NUMERIC(4, 1) NOT NULL DEFAULT 0,
  orders INT NOT NULL DEFAULT 0,
  commission_rate NUMERIC(5, 2) NOT NULL DEFAULT 0,
  affiliate_url TEXT NOT NULL,
  source_query TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'removed')),
  ai_written BOOLEAN NOT NULL DEFAULT FALSE,
  reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- שדות שנוספו בגרסה השנייה (עמוד מוצר, אמון, רענון מחירים, תור חכם)
ALTER TABLE public.shop_products
  ADD COLUMN IF NOT EXISTS score NUMERIC(6, 2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS why TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS shipping_days INT NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS sub_id TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS price_updated_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS missing_count INT NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS images JSONB NOT NULL DEFAULT '[]'::jsonb;

-- גלריית תמונות לכל מוצר: [{ "url": "...", "approved": true/false }]
-- המוצר נשמר גם ב-image_url (התמונה הראשית) כדי לא לשבור קוד קיים.
UPDATE public.shop_products
SET images = jsonb_build_array(jsonb_build_object('url', image_url, 'approved', TRUE))
WHERE COALESCE(image_url, '') <> ''
  AND (images IS NULL OR jsonb_array_length(images) = 0);

-- סטטוס 'removed' מתווסף למוצרים שהוסרו אוטומטית כי הקישור/המלאי נגמר
ALTER TABLE public.shop_products DROP CONSTRAINT IF EXISTS shop_products_status_check;
ALTER TABLE public.shop_products
  ADD CONSTRAINT shop_products_status_check
  CHECK (status IN ('pending', 'approved', 'rejected', 'removed'));

CREATE INDEX IF NOT EXISTS idx_shop_products_status ON public.shop_products (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_shop_products_category ON public.shop_products (category);
CREATE INDEX IF NOT EXISTS idx_shop_products_score ON public.shop_products (status, score DESC);

ALTER TABLE public.shop_products ENABLE ROW LEVEL SECURITY;

-- הציבור רואה רק מוצרים שאושרו
DROP POLICY IF EXISTS "Public can read approved products" ON public.shop_products;
CREATE POLICY "Public can read approved products"
  ON public.shop_products FOR SELECT
  TO anon, authenticated
  USING (status = 'approved');

-- מנהלים רואים ומנהלים הכל
DROP POLICY IF EXISTS "Admins can read all products" ON public.shop_products;
CREATE POLICY "Admins can read all products"
  ON public.shop_products FOR SELECT
  TO authenticated
  USING (EXISTS (SELECT 1 FROM public.admins WHERE email = auth.jwt() ->> 'email'));

-- מנהלים יכולים גם להוסיף מוצר ידנית מהפאנל (הוא נכנס תמיד כ'ממתין')
DROP POLICY IF EXISTS "Admins can insert products" ON public.shop_products;
CREATE POLICY "Admins can insert products"
  ON public.shop_products FOR INSERT
  TO authenticated
  WITH CHECK (
    EXISTS (SELECT 1 FROM public.admins WHERE email = auth.jwt() ->> 'email')
    AND status = 'pending'
  );

DROP POLICY IF EXISTS "Admins can update products" ON public.shop_products;
CREATE POLICY "Admins can update products"
  ON public.shop_products FOR UPDATE
  TO authenticated
  USING (EXISTS (SELECT 1 FROM public.admins WHERE email = auth.jwt() ->> 'email'))
  WITH CHECK (EXISTS (SELECT 1 FROM public.admins WHERE email = auth.jwt() ->> 'email'));

DROP POLICY IF EXISTS "Admins can delete products" ON public.shop_products;
CREATE POLICY "Admins can delete products"
  ON public.shop_products FOR DELETE
  TO authenticated
  USING (EXISTS (SELECT 1 FROM public.admins WHERE email = auth.jwt() ->> 'email'));

