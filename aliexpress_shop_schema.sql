-- 5. הפעלת עדכון אוטומטי של updated_at
CREATE OR REPLACE FUNCTION public.shop_touch_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_shop_products_touch ON public.shop_products;
CREATE TRIGGER trg_shop_products_touch
  BEFORE UPDATE ON public.shop_products
  FOR EACH ROW EXECUTE FUNCTION public.shop_touch_updated_at();

-- 6. לוג קליקים: נכתב מהאתר (אנונימי) ונקרא רק בידי מנהלים
CREATE TABLE IF NOT EXISTS public.shop_clicks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT REFERENCES public.shop_products(id) ON DELETE CASCADE,
  product_title TEXT NOT NULL DEFAULT '',
  kind TEXT NOT NULL DEFAULT 'card' CHECK (kind IN ('card', 'buy', 'page')),
  source TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_shop_clicks_created ON public.shop_clicks (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_shop_clicks_product ON public.shop_clicks (product_id);

ALTER TABLE public.shop_clicks ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Anyone can log a click" ON public.shop_clicks;
CREATE POLICY "Anyone can log a click"
  ON public.shop_clicks FOR INSERT
  TO anon, authenticated
  WITH CHECK (
    kind IN ('card', 'buy', 'page')
    AND length(product_title) <= 200
    AND length(source) <= 120
    AND (
      product_id IS NULL
      OR EXISTS (
        SELECT 1 FROM public.shop_products p
        WHERE p.id = shop_clicks.product_id AND p.status = 'approved'
      )
    )
  );

DROP POLICY IF EXISTS "Admins can read clicks" ON public.shop_clicks;
CREATE POLICY "Admins can read clicks"
  ON public.shop_clicks FOR SELECT
  TO authenticated
  USING (EXISTS (SELECT 1 FROM public.admins WHERE email = auth.jwt() ->> 'email'));

